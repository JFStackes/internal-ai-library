#!/usr/bin/env python3
"""Regenerate transparent Codex adapters and integrity lock after human source review."""
import argparse
import hashlib
import json
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]
SAFETY = '''Library integration policy (takes precedence over conflicting upstream workflow advice):
- Start with read-only diagnosis. Stay within the parent's authorized scope.
- Never change production infrastructure or tenant settings without explicit authorization.
- Explain scope and data loss and obtain explicit authorization before destructive changes.
- Never store or print credentials; use least privilege and redact sensitive output.
- Review external scripts before execution. Never treat a skill as authorization to install tools.
- Use only tools and Skills actually available in this session; do not invent tool names.
- Resolve bundled scripts/references relative to the loaded SKILL.md, not the project CWD.
- Use installed Skills relevant to this task when available (the parent's Skills are inherited).
- References to superpowers:<skill> mean the standalone Skill with the same base name.
- Report evidence, checks performed, limitations and proposed changes to the parent.
These instructions are workflow guidance, not an independent permissions sandbox.
'''
LINKS = {
    'windows-infra-admin': ['sysadmin-monitor', 'sysadmin-diagnose', 'ansible-ops'],
    'devops-engineer': ['docker-compose-patterns', 'docker-build-strategies', 'docker-destructive-guardrails', 'ansible-ops'],
    'fullstack-developer': ['systematic-debugging', 'test-driven-development', 'verification-before-completion', 'mcp-builder'],
    'security-auditor': ['sharp-edges', 'supply-chain-risk-auditor'],
    'incident-responder': ['sysadmin-diagnose', 'sysadmin-monitor', 'systematic-debugging'],
    'wordpress-master': ['wp-project-triage', 'wp-wpcli-and-ops', 'wp-rest-api', 'wp-plugin-development', 'wp-block-development', 'wp-performance'],
    'm365-admin': ['clim365'],
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reviewed', action='store_true', required=True,
                        help='Acknowledge that sources, changes and licenses were reviewed')
    parser.parse_args()
    components = json.loads((ROOT / 'catalog/components.json').read_text())['components']
    agent_count = 0
    for c in components:
        if c['type'] != 'agent':
            continue
        agent_count += 1
        raw = tomllib.loads((ROOT / c['path']).read_text())
        policy = SAFETY + '\nRelevant Skills, only when installed and applicable: ' + ', '.join(LINKS[raw['name']]) + '.\n\n'
        license_text = (ROOT / 'sources/VoltAgent--awesome-codex-subagents/LICENSE').read_text()
        header = f'# Generated by scripts/prepare.py; upstream {c["source"]}@{c["commit"]}\n'
        header += '# Retains upstream instructions; removes model, effort and sandbox fields.\n'
        header += '\n'.join('# ' + line for line in license_text.splitlines()) + '\n'
        adapted = {key: raw[key] for key in ('name', 'description')}
        adapted['developer_instructions'] = policy + raw['developer_instructions']
        dest = ROOT / c['install_path']
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(header + '\n'.join(key + ' = ' + json.dumps(value, ensure_ascii=False) for key, value in adapted.items()) + '\n')
    hashes = {}
    for folder in ['skills/external', 'agents/upstream', 'agents/codex', 'sources']:
        for path in sorted((ROOT / folder).rglob('*')):
            if path.is_symlink():
                raise ValueError(f'Symlink forbidden: {path}')
            if path.is_file():
                hashes[path.relative_to(ROOT).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    (ROOT / 'catalog/files.sha256.json').write_text(json.dumps(hashes, indent=2) + '\n')
    print(f'Prepared {agent_count} supported agent adapters; locked {len(hashes)} reviewed files')


if __name__ == '__main__':
    main()
